-- Poznávačka rostlin: pokrok uživatelů. Spustit v Supabase SQL editoru (nebo supabase db push).

create table if not exists public.progress (
  user_id   uuid not null references auth.users(id) on delete cascade,
  set_id    text not null,
  item_id   text not null,
  weight    real not null default 1,
  streak    int  not null default 0,
  correct   int  not null default 0,
  wrong     int  not null default 0,
  last_seen timestamptz,
  primary key (user_id, set_id, item_id)
);

create table if not exists public.answers (
  id          bigint generated by default as identity primary key,
  user_id     uuid not null references auth.users(id) on delete cascade,
  set_id      text not null,
  item_id     text not null,
  correct     boolean not null,
  answered_at timestamptz not null default now()
);

create index if not exists answers_user_set_idx on public.answers (user_id, set_id, answered_at desc);

alter table public.progress enable row level security;
alter table public.answers  enable row level security;

-- Každý vidí a mění jen své vlastní řádky.
create policy "progress: vlastní řádky" on public.progress
  for all to authenticated
  using ((select auth.uid()) = user_id)
  with check ((select auth.uid()) = user_id);

create policy "answers: vlastní řádky" on public.answers
  for all to authenticated
  using ((select auth.uid()) = user_id)
  with check ((select auth.uid()) = user_id);
